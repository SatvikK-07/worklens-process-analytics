def _generate_figures(results_dir: Path, report_dir: Path) -> None:
    figures = report_dir / "figures"
    figures.mkdir(parents=True, exist_ok=True)
    metrics = json.loads((results_dir / "long_case_n3_metrics.json").read_text())
    predictions = pd.read_csv(results_dir / "long_case_n3_predictions.csv")
    target = predictions["target"]
    probability = predictions["probability"]

    if target.nunique() == 2:
        RocCurveDisplay.from_predictions(target, probability)
    else:
        plt.text(0.5, 0.5, "ROC undefined: holdout has one class", ha="center")
        plt.axis("off")
    plt.tight_layout()
    plt.savefig(figures / "real_long_case_roc_curve.png", dpi=160)
    plt.close()

    if target.sum() > 0:
        PrecisionRecallDisplay.from_predictions(target, probability)
    else:
        plt.text(0.5, 0.5, "PR curve undefined: no positive holdout cases", ha="center")
        plt.axis("off")
    plt.tight_layout()
    plt.savefig(figures / "real_long_case_pr_curve.png", dpi=160)
    plt.close()

    matrix = metrics["models"][metrics["selected_model"]]["confusion_matrix"]
    ConfusionMatrixDisplay(np.asarray(matrix), display_labels=[0, 1]).plot(cmap="Greens")
    plt.tight_layout()
    plt.savefig(figures / "real_long_case_confusion_matrix.png", dpi=160)
    plt.close()

    calibration = metrics["calibration"]
    plt.plot(
        calibration["mean_predicted_probability"],
        calibration["fraction_positive"],
        marker="o",
        label="Observed",
    )
    plt.plot([0, 1], [0, 1], linestyle="--", color="gray", label="Ideal")
    plt.xlabel("Mean predicted probability")
    plt.ylabel("Observed positive rate")
    plt.legend()
    plt.tight_layout()
    plt.savefig(figures / "real_long_case_calibration_curve.png", dpi=160)
    plt.close()

    importance = pd.read_csv(results_dir / "long_case_n3_feature_importance.csv").head(15)
    importance = importance.sort_values("importance")
    plt.barh(importance["feature"], importance["importance"], color="#19a974")
    plt.tight_layout()
    plt.savefig(figures / "real_long_case_feature_importance.png", dpi=160)
    plt.close()

    regression = pd.read_csv(results_dir / "remaining_time_n3_predictions.csv")
    residual = regression["remaining_time_hours"] - regression["prediction"]
    plt.scatter(regression["prediction"], residual, alpha=0.6, s=18)
    plt.axhline(0, linestyle="--", color="gray")
    plt.xlabel("Predicted remaining hours")
    plt.ylabel("Residual hours")
    plt.tight_layout()
    plt.savefig(figures / "real_remaining_time_residuals.png", dpi=160)
    plt.close()

    regression_metrics = json.loads((results_dir / "remaining_time_n3_metrics.json").read_text())
    buckets = pd.DataFrame(regression_metrics["error_by_duration_bucket"])
    plt.bar(buckets["duration_bucket"], buckets["mae"], color="#295c49")
    plt.xticks(rotation=25, ha="right")
    plt.ylabel("MAE (hours)")
    plt.tight_layout()
    plt.savefig(figures / "real_remaining_time_error_by_bucket.png", dpi=160)
    plt.close()


def _write_report(
    events: pd.DataFrame,
    results: dict[str, dict],
    report_path: Path,
    sample: bool,
) -> None:
    classification = results["long_case_n3"]
    regression = results["remaining_time_n3"]
    c_metrics = classification["models"][classification["selected_model"]]
    r_metrics = regression["models"][regression["selected_model"]]
    baseline_mae = regression["models"]["Median Baseline"]["mae"]
    regression_conclusion = (
        "The selected model beat the temporal holdout median baseline."
        if r_metrics["mae"] < baseline_mae
        else "The selected model did not beat the temporal holdout median baseline."
    )
    label = "sample code-path validation" if sample else "full public event-log experiment"
    report_path.parent.mkdir(parents=True, exist_ok=True)

    def display(value: float | None, digits: int = 4) -> str:
        return "not defined for this split" if value is None else f"{value:.{digits}f}"

    report_path.write_text(
        f"""# Real event-log model report

Generated by `real_eventlog_experiments/scripts/run_all_real_experiments.py`.

Run type: **{label}**

Dataset: Sepsis Cases Event Log ({events["case_id"].nunique():,} cases,
{len(events):,} events).

## Long-case classification (N=3)

- Validation-selected target: {classification["selected_target"]}
- Target definition: {classification["target_definition"]}
- Target threshold: {classification["target_threshold_hours"]:.2f} hours
- Selected model: {classification["selected_model"]}
- ROC-AUC: {display(c_metrics["roc_auc"])}
- PR-AUC: {display(c_metrics["pr_auc"])}
- Precision: {display(c_metrics["precision"])}
- Recall: {display(c_metrics["recall"])}
- F1: {display(c_metrics["f1"])}
- Balanced accuracy: {display(c_metrics["balanced_accuracy"])}
- Brier score: {display(c_metrics["brier_score"])}

## Remaining-time regression (N=3)

- Selected model: {regression["selected_model"]}
- MAE: {r_metrics["mae"]:.2f} hours
- RMSE: {r_metrics["rmse"]:.2f} hours
- Median absolute error: {r_metrics["median_absolute_error"]:.2f} hours
- R²: {r_metrics["r2"]:.4f}
- Improvement over median baseline: {r_metrics.get("baseline_improvement_pct", 0):.2f}%
- Median-baseline MAE: {baseline_mae:.2f} hours

**Holdout conclusion:** {regression_conclusion}

## Scope

These results validate prefix-based modelling methodology on a real hospital event
log. They do not validate healthcare-claims performance, clinical decisions, or
production readiness.
"""
    )


def _write_summary(
    events: pd.DataFrame,
    results: dict[str, dict],
    results_dir: Path,
    sample: bool,
) -> None:
    prefixes = {}
    comparison_rows = []
    for prefix_length in (3, 5):
        classification = results[f"long_case_n{prefix_length}"]
        regression = results[f"remaining_time_n{prefix_length}"]
        classification_metrics = classification["models"][classification["selected_model"]]
        regression_metrics = regression["models"][regression["selected_model"]]
        prefixes[f"n{prefix_length}"] = {
            "classification": {
                "selected_target": classification["selected_target"],
                "target_definition": classification["target_definition"],
                "selected_model": classification["selected_model"],
                "test_metrics": classification_metrics,
                "temporal_vs_random": classification["temporal_vs_random"],
                "target_variants": classification["target_variants"],
            },
            "regression": {
                "selected_model": regression["selected_model"],
                "test_metrics": regression_metrics,
                "temporal_vs_random": regression["temporal_vs_random"],
                "beats_median_baseline": regression["beats_median_baseline"],
                "baseline_mae": regression["baseline_mae"],
            },
        }
        comparison_rows.extend(
            [
                {
                    "prefix_length": prefix_length,
                    "task": "long_case_classification",
                    "target_variant": classification["selected_target"],
                    "selected_model": classification["selected_model"],
                    "primary_metric": "pr_auc",
                    "temporal_score": classification_metrics["pr_auc"],
                    "random_score": classification["temporal_vs_random"]["random"]["pr_auc"],
                },
                {
                    "prefix_length": prefix_length,
                    "task": "remaining_time_regression",
                    "target_variant": "remaining_time_hours",
                    "selected_model": regression["selected_model"],
                    "primary_metric": "mae",
                    "temporal_score": regression_metrics["mae"],
                    "random_score": regression["temporal_vs_random"]["random"]["mae"],
                },
            ]
        )
    case_paths = (
        events.sort_values(["case_id", "timestamp"])
        .groupby("case_id")["activity"]
        .agg(lambda values: " → ".join(values.astype(str)))
    )
    event_counts = events.groupby("case_id").size()
    repeated = events.groupby("case_id")["activity"].agg(
        lambda values: len(values) > len(set(values))
    )
    transition_rows = []
    ordered = events.sort_values(["case_id", "timestamp"]).copy()
    ordered["next_activity"] = ordered.groupby("case_id")["activity"].shift(-1)
    for (source, target), count in (
        ordered.dropna(subset=["next_activity"])
        .groupby(["activity", "next_activity"])
        .size()
        .nlargest(10)
        .items()
    ):
        transition_rows.append({"source": str(source), "target": str(target), "count": int(count)})
    summary = {
        "dataset": "Sepsis Cases Event Log",
        "source": "4TU.ResearchData DOI 10.4121/uuid:915d2bfb-7e84-49ad-a286-dc35f063a460",
        "run_type": "sample_code_path" if sample else "full_public_event_log",
        "case_count": int(events["case_id"].nunique()),
        "event_count": int(len(events)),
        "activity_count": int(events["activity"].nunique()),
        "variant_count": int(case_paths.nunique()),
        "start_timestamp": pd.to_datetime(events["timestamp"], utc=True).min().isoformat(),
        "end_timestamp": pd.to_datetime(events["timestamp"], utc=True).max().isoformat(),
        "average_events_per_case": float(event_counts.mean()),
        "median_events_per_case": float(event_counts.median()),
        "missing_values": {column: int(events[column].isna().sum()) for column in events.columns},
        "process_validation": {
            "chronology_check": bool(
                events.sort_values(["case_id", "timestamp"])
                .groupby("case_id")["timestamp"]
                .apply(lambda values: values.is_monotonic_increasing)
                .all()
            ),
            "transition_analysis": bool(transition_rows),
            "variant_extraction": bool(len(case_paths)),
            "rework_case_rate": float(repeated.mean()),
            "top_variants": [
                {"variant": str(variant), "cases": int(count)}
                for variant, count in case_paths.value_counts().head(10).items()
            ],
            "top_transitions": transition_rows,
        },
        "validation": "chronological_70_15_15_primary",
        "prefixes": prefixes,
    }
    (results_dir / "experiment_summary.json").write_text(json.dumps(summary, indent=2))
    pd.DataFrame(comparison_rows).to_csv(results_dir / "experiment_comparison.csv", index=False)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--input",
        type=Path,
        default=Path("data/real/raw/sepsis_cases.xes.gz"),
    )
    parser.add_argument("--sample", action="store_true")
    parser.add_argument("--output-dir", type=Path)
    parser.add_argument("--report-dir", type=Path)
    args = parser.parse_args()
    if args.sample and args.input == Path("data/real/raw/sepsis_cases.xes.gz"):
        args.input = Path("data/sample/sepsis_events_sample.csv")
    events = load_eventlog(args.input)
    results_dir = args.output_dir or (
        Path("/tmp/worklens-real-eventlog-sample/results")
        if args.sample
        else Path("real_eventlog_experiments/results")
    )
    report_dir = args.report_dir or (
        Path("/tmp/worklens-real-eventlog-sample/reports") if args.sample else Path("reports")
    )
    results_dir.mkdir(parents=True, exist_ok=True)
    results = {}
    for prefix_length in (3, 5):
        results[f"long_case_n{prefix_length}"] = run_long_case_experiment(
            events, prefix_length, results_dir
        )
        results[f"remaining_time_n{prefix_length}"] = run_remaining_time_experiment(
            events, prefix_length, results_dir
        )
    _write_summary(events, results, results_dir, args.sample)
    _generate_figures(results_dir, report_dir)
    _write_report(
        events,
        results,
        report_dir / "real_eventlog_model_report.md",
        args.sample,
    )
    print("Real event-log experiments complete")


if __name__ == "__main__":
    main()
